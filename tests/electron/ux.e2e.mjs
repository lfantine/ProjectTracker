scenarios['scroll de page, titres persistants, aide rapide et édition visuelle des shortcuts'] = async ({ launch }) => {
  const { page } = await launch({ PROJECT_TRACKER_MODULES: '1' })
  await page.setViewportSize({ width: 1360, height: 800 })
  await page.getByText('Projets actifs', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Add a shortcut', exact: true }).click()
  await page.getByRole('button', { name: 'Icône Calendrier', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nom', exact: true }).fill('Planning visuel')
  await expect(page.getByLabel('Aperçu du shortcut')).toContainText('Planning visuel')
  await page.screenshot({ path: '/tmp/amber-ux2-shortcut.png' })
  await page.getByRole('button', { name: 'Ajouter le shortcut', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Planning visuel', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add a shortcut', exact: true }).click()
  await page.getByRole('button', { name: 'Groupe', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nom', exact: true }).fill('Travail')
  await page.getByRole('button', { name: 'Créer le groupe', exact: true }).click()
  await page.getByRole('button', { name: 'Renommer Travail', exact: true }).click()
  const name = page.getByRole('textbox', { name: 'Nom du groupe', exact: true })
  await name.fill('Projets persos'); await name.press('Enter')
  await expect(page.getByRole('button', { name: 'Groupe Projets persos', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Renommer Projets persos', exact: true }).click()
  await name.fill('Ne pas conserver'); await name.press('Escape')
  await expect(page.getByRole('button', { name: 'Groupe Projets persos', exact: true })).toBeVisible()
  await page.evaluate(() => window.next.router.push('/week'))
  const frame = page.frameLocator('iframe').first()
  await frame.getByRole('button', { name: 'Gérer les semaines', exact: true }).waitFor()
  await frame.locator('body').evaluate(async () => {
    const sdk = await ProjectTracker.ready, context = await sdk.call('context.get', {})
    const address = { collection: 'week', id: 'schedule', scope: 'instance', instanceId: context.instance.instanceId }
    const stored = await sdk.storage.get(address)
    await sdk.storage.put({ ...address, expectedRevision: stored.revision, value: { ...stored.value, slots: [{ id: 'long', title: 'Long événement lisible', day: 0, start: '00:00', end: '20:00', color: '#5588bb' }] } })
  })
  const event = frame.locator('.week-slot').first()
  await expect(event).toContainText('Long événement lisible')
  await expect.poll(async () => (await page.locator('iframe').first().boundingBox()).height).toBeGreaterThan(1200)
  const scroller = page.locator('[data-page-scroll]')
  assert.equal(await frame.locator('.week-grid').evaluate(node => getComputedStyle(node).overflowY), 'visible')
  assert.equal(await frame.locator('body').evaluate(() => document.documentElement.scrollHeight > innerHeight + 2), false)
  // Labels begin at the top, not vertically centred in a multi-hour button.
  const top = await event.locator('.week-slot-caption').boundingBox(), rect = await event.boundingBox()
  assert.ok(top.y - rect.y < 8)
  const canvas = await frame.locator('.week-canvas').first().boundingBox()
  assert.ok(rect.x - canvas.x < 5, 'no permanent wake-marker gutter')
  const help = frame.getByRole('button', { name: 'Aide du calendrier', exact: true })
  const helpBox = await help.boundingBox(); assert.ok(helpBox.width <= 24 && helpBox.height <= 24)
  await help.hover()
  await expect(frame.getByRole('tooltip')).toBeVisible({ timeout: 1600 })
  await help.press('Escape'); await expect(frame.getByRole('tooltip')).toHaveCount(0)
  // The parent page, not the embedded calendar, owns vertical scrolling.
  await scroller.evaluate(node => { node.scrollTop = 550 })
  await expect.poll(async () => frame.locator('html').evaluate(node => parseFloat(node.style.getPropertyValue('--amber-viewport-top')))).toBeGreaterThan(350)
  await page.waitForTimeout(80)
  const sticky = await event.locator('.week-slot-caption').boundingBox(), visible = await scroller.boundingBox()
  assert.ok(sticky.y >= visible.y && sticky.y <= visible.y + 80, `sticky label outside visible page: ${sticky.y} vs ${visible.y}`)
  await page.screenshot({ path: '/tmp/amber-ux2-scroll.png' })
  await event.click({ position: { x: 25, y: 600 } }); await expect(event).toHaveAttribute('aria-pressed', 'true')
  const otherCanvas = frame.locator('.week-canvas').nth(1)
  await otherCanvas.click({ position: { x: 45, y: 600 } })
  await expect(event).toHaveAttribute('aria-pressed', 'false')
  // A modal opened while scrolled must remain in the visible parent viewport.
  await event.click({ position: { x: 25, y: 600 } }); await event.press('Space')
  const dialog = frame.getByRole('dialog', { name: 'Modifier le créneau', exact: true })
  await expect(dialog).toBeVisible()
  const modal = await dialog.boundingBox()
  assert.ok(modal.y >= visible.y && modal.y + modal.height <= visible.y + visible.height + 2)
  await page.screenshot({ path: '/tmp/amber-ux2-dialog-scroll.png' })
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
}
