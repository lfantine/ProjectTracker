import assert from 'node:assert/strict'
export const scenarios = {
  async 'composition persistante et navigation toujours récupérable'({ launch, close }) {
    let { page } = await launch()
    await page.getByText('Projets actifs', { exact: true }).waitFor({ timeout: 30000 })
    const run = command => page.evaluate(async command => {
      const snapshot = await window.api.composition.snapshot()
      if (!snapshot.ok) throw new Error(snapshot.error.message)
      return window.api.composition.command({ command, expectedRevision: snapshot.value.revision, operationId: crypto.randomUUID() })
    }, command)
    const created = await run({ kind: 'dashboard.duplicate', id: 'dash-home', name: 'Dashboard test' })
    assert.equal(created.ok, true)
    const id = created.value.id
    await page.evaluate(id => window.next.router.push(`/dashboard?id=${id}`), id)
    await page.getByRole('button', { name: 'Personnaliser le dashboard', exact: true }).click()
    const handle = page.getByRole('button', { name: 'Déplacer Projets actifs', exact: true })
    await handle.focus(); await handle.press('ArrowDown')
    await page.waitForFunction(async id => {
      const value = await window.api.composition.snapshot()
      return value.ok && value.value.dashboards.find(item => item.id === id)?.widgets.some(item => item.layouts.md || item.layouts.sm || (item.layouts.lg?.y > 0))
    }, id)
    // Pointer gesture persists only at its end; iframe interaction is disabled during it.
    const grid = page.locator('.dashboard-grid')
    const beforeDrag = await page.evaluate(() => window.api.composition.snapshot())
    const box = await handle.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 96, { steps: 8 })
    assert.ok(await grid.evaluate(node => node.classList.contains('gesturing')))
    const duringDrag = await page.evaluate(() => window.api.composition.snapshot())
    assert.equal(duringDrag.value.revision, beforeDrag.value.revision, 'aucune écriture pendant le geste')
    await page.mouse.up()
    await page.waitForFunction(async revision => (await window.api.composition.snapshot()).value.revision > revision, beforeDrag.value.revision)
    await page.waitForFunction(() => !document.querySelector('.dashboard-grid')?.classList.contains('gesturing'))
    await page.waitForFunction(() => !document.querySelector('.widget-move-handle')?.disabled)
    const resize = page.locator('[data-placement]').first().locator('.react-resizable-handle-se')
    const beforeResize = await page.evaluate(() => window.api.composition.snapshot())
    const grip = await resize.boundingBox()
    await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
    await page.mouse.down(); await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2 + 96, { steps: 8 }); await page.mouse.up()
    await page.waitForFunction(() => !document.querySelector('.widget-move-handle')?.disabled)
    await page.waitForFunction(async revision => (await window.api.composition.snapshot()).value.revision > revision, beforeResize.value.revision)
    for (const [width, breakpoint] of [[1700, 'lg'], [1200, 'md'], [800, 'sm']]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.locator(`.dashboard-grid[data-breakpoint="${breakpoint}"]`).waitFor()
      await handle.focus(); await handle.press('ArrowDown')
      await page.waitForFunction(async ({ id, breakpoint }) => {
        const value = await window.api.composition.snapshot()
        return value.ok && value.value.dashboards.find(item => item.id === id)?.widgets.every(item => item.layouts[breakpoint])
      }, { id, breakpoint })
      await page.waitForFunction(() => !document.querySelector('.widget-move-handle')?.disabled)
    }
    const snapshot = await page.evaluate(() => window.api.composition.snapshot())
    const savedLayouts = snapshot.value.dashboards.find(item => item.id === id).widgets.map(item => item.layouts)
    for (const entry of snapshot.value.sidebar) assert.equal((await run({ kind: 'sidebar.update', id: entry.id, label: entry.label, icon: entry.icon, target: entry.target, hidden: true })).ok, true)
    await page.getByRole('link', { name: 'Personnalisation', exact: true }).click()
    await page.getByRole('button', { name: /CORE.*Apparence/ }).click()
    await page.getByRole('button', { name: 'Restaurer la navigation par défaut', exact: true }).waitFor()
    await page.getByRole('link', { name: 'Réglages', exact: true }).waitFor()
    await close(); ({ page } = await launch())
    const restored = await page.evaluate(() => window.api.composition.snapshot())
    assert.ok(restored.ok && restored.value.dashboards.some(item => item.id === id))
    assert.deepEqual(restored.value.dashboards.find(item => item.id === id).widgets.map(item => item.layouts), savedLayouts)
    assert.ok(restored.value.sidebar.every(item => item.hidden))
    await page.getByRole('link', { name: 'Personnalisation', exact: true }).click()
    await page.getByRole('button', { name: /CORE.*Apparence/ }).click()
    await page.getByRole('button', { name: 'Restaurer la navigation par défaut', exact: true }).click()
    await page.getByRole('link', { name: 'Projets', exact: true }).waitFor()
  },
}
