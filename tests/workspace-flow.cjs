const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2017 } }).outputText, filename)
const { mergeAiDraftChanges, buildAiDraftProposal } = require('../renderer/lib/aiCreation.ts')
const { readProjectTabSession, openProjectTab, closeProjectTab, projectTabForShortcut } = require('../renderer/lib/projectTabs.ts')
const { removeNoteFromData, restoreNoteFromData } = require('../renderer/lib/noteOperations.ts')
const { normalizeAppData } = require('../renderer/lib/types.ts')

const original = { type: 'project', name: 'Project', description: 'Original', tasks: [{ id: 'parent', name: 'Parent', content: 'Keep', status: 'en_cours', children: [{ id: 'child', name: 'Child', status: 'fait', content: '', children: [] }] }], links: [{ id: 'link', title: 'Docs', url: 'https://example.com' }], noteActions: [{ action: 'create', title: 'Keep note', content: 'Keep note content', projectIds: ['$self'] }] }
const first = mergeAiDraftChanges(original, { type: 'project', description: 'Revised' })
const second = mergeAiDraftChanges(first, { type: 'project', name: 'Renamed' })
assert.equal(second.tasks, original.tasks)
assert.equal(second.links, original.links)
assert.equal(second.noteActions, original.noteActions)
assert.equal(first.name, 'Project') // Previous snapshot can still be restored.
assert.equal(original.description, 'Original')
assert.equal(second.description, 'Revised')
assert.deepEqual(mergeAiDraftChanges(second, { type: 'project', links: [] }).links, [])
assert.throws(() => mergeAiDraftChanges(second, { type: 'note', content: 'Wrong type' }))
assert.throws(() => mergeAiDraftChanges({ ...second, id: 'original' }, { type: 'project', id: 'other' }))
assert.throws(() => mergeAiDraftChanges({ ...second, createdAt: 'original' }, { type: 'project', createdAt: 'other' }))
// Preview objects may omit IDs; refinement context must retain complete stored entries.
const preview = { type: 'project', name: 'Project', tasks: [{ name: 'Parent', children: [] }] }
const context = buildAiDraftProposal(preview, { type: 'project', description: 'Revised' }, { ...original, type: 'dev', id: 'project-id' })
assert.equal(context.type, 'project')
assert.equal(context.id, 'project-id')
assert.equal(context.tasks, original.tasks)
assert.equal(context.tasks[0].children[0].status, 'fait')
assert.equal(context.description, 'Revised')

let tabs = openProjectTab([], 'alpha')
assert.deepEqual(openProjectTab(tabs, 'beta'), [{ projectId: 'beta', pinned: false }])
tabs[0] = { ...tabs[0], pinned: true }
tabs = openProjectTab(tabs, 'beta')
assert.equal(openProjectTab(tabs, 'beta'), tabs)
assert.deepEqual(openProjectTab(tabs, 'gamma'), [{ projectId: 'alpha', pinned: true }, { projectId: 'gamma', pinned: false }])
assert.deepEqual(openProjectTab(tabs, 'alpha'), [{ projectId: 'alpha', pinned: true }])
assert.deepEqual(closeProjectTab(tabs, 'alpha'), tabs)
assert.equal(projectTabForShortcut(tabs, '1'), 'alpha')
assert.equal(projectTabForShortcut(tabs, '2'), 'beta')
assert.equal(projectTabForShortcut(tabs, '9'), undefined)
assert.equal(projectTabForShortcut(tabs, '0'), undefined)
const saved = readProjectTabSession(JSON.parse(JSON.stringify({ tabs, activeId: 'beta' })), ['alpha', 'beta'])
assert.equal(saved.activeId, 'beta')
assert.equal(saved.tabs[0].pinned, true)
assert.deepEqual(readProjectTabSession({ tabs: [...tabs, tabs[0], { projectId: 'deleted' }, null], activeId: 'deleted' }, ['alpha', 'beta']), { tabs, activeId: undefined })
assert.deepEqual(readProjectTabSession('invalid', []), { tabs: [], activeId: undefined })
assert.equal(closeProjectTab(tabs, 'beta').length, 1)

const note = { id: 'note', title: 'Important', content: '## Keep all content', tags: ['tag'], raw: true, createdAt: 'before', updatedAt: 'before' }
const pinnedModule = { id: 'pinned', type: 'note', refId: 'note' }
const data = normalizeAppData({ projects: [{ id: 'linked', noteIds: ['note'], layout: [pinnedModule, { id: 'tasks', type: 'tasks' }] }, { id: 'legacy', noteIds: ['note'] }], notes: [note] })
const deleted = removeNoteFromData(data, 'note')
assert.equal(deleted.notes.length, 0)
assert.equal(deleted.trashedNotes.length, 1)
assert.equal(deleted.trashedNotes[0].note, note)
assert.equal(removeNoteFromData(deleted, 'note'), deleted)
assert.equal(deleted.projects[0].layout.length, 1)
const restored = restoreNoteFromData(normalizeAppData(JSON.parse(JSON.stringify(deleted))), 'note')
assert.deepEqual(restored.notes[0], note)
assert.deepEqual(restored.projects[0].noteIds, ['note'])
assert.deepEqual(restored.projects[0].layout.find(item => item.id === 'pinned'), pinnedModule)
assert.deepEqual(restored.projects[1].noteIds, ['note'])
assert.equal(restored.trashedNotes.length, 0)
assert.equal(restoreNoteFromData(restored, 'note'), restored)
const deletedProject = { ...deleted, projects: [] }
assert.equal(restoreNoteFromData(deletedProject, 'note').notes.length, 1)
assert.equal(restoreNoteFromData(deletedProject, 'note').projects.length, 0)
console.log('Workspace flow regression passed: iterative AI patches and metadata, tab persistence and shortcuts, trash persistence and restoration')
