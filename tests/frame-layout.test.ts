import { afterEach, expect, it, vi } from 'vitest'
import { fitContribution, observeContentSize, FRAME_SIZE, FRAME_VIEWPORT, MAX_FRAME_HEIGHT } from '../sdk/src/layout'
const cleanups: (() => void)[] = []
afterEach(() => { cleanups.splice(0).forEach(stop => stop()); vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.useRealTimers(); document.body.replaceChildren(); document.documentElement.removeAttribute('data-amber-layout'); document.documentElement.removeAttribute('style') })
it('fits only its exact registered frame and rejects malformed/oversized presentation messages', () => {
  const frame = document.createElement('iframe'); document.body.append(frame)
  cleanups.push(fitContribution(frame, 'https://package.example'))
  const emit = (data: unknown, source = frame.contentWindow, origin = 'https://package.example') => window.dispatchEvent(new MessageEvent('message', { source, origin, data }))
  emit({ type: FRAME_SIZE, height: 900 }, window)
  emit({ type: FRAME_SIZE, height: 900 }, frame.contentWindow, 'https://foreign.example')
  for (const height of [-1, 0, 1.1, NaN, Infinity, MAX_FRAME_HEIGHT + 1, '900']) emit({ type: FRAME_SIZE, height })
  emit({ type: FRAME_SIZE, height: 900, command: 'forged' })
  expect(frame.style.height).toBe('')
  emit({ type: FRAME_SIZE, height: 900 }); expect(frame.style.height).toBe('900px')
  emit({ type: FRAME_SIZE, height: 120 }); expect(frame.style.height).toBe('120px')
  cleanups.pop()!(); emit({ type: FRAME_SIZE, height: 800 }); expect(frame.style.height).toBe('120px')
})
it('relays the visible parent-page viewport without exposing data or DOM access', () => {
  vi.useFakeTimers()
  const scroller = document.createElement('div'); scroller.dataset.pageScroll = ''
  const frame = document.createElement('iframe'); scroller.append(frame); document.body.append(scroller)
  vi.spyOn(frame, 'getBoundingClientRect').mockReturnValue({ top: -100, height: 1200 } as DOMRect)
  vi.spyOn(scroller, 'getBoundingClientRect').mockReturnValue({ top: 76, bottom: 700 } as DOMRect)
  const post = vi.spyOn(frame.contentWindow!, 'postMessage')
  cleanups.push(fitContribution(frame, 'https://package.example'))
  document.dispatchEvent(new Event('scroll')); vi.advanceTimersByTime(20)
  expect(post).toHaveBeenCalledWith({ type: FRAME_VIEWPORT, top: 176, height: 624 }, 'https://package.example')
})
it('measures intrinsic body height and accepts only bounded parent viewport data', () => {
  vi.useFakeTimers()
  const disconnect = vi.fn()
  vi.stubGlobal('ResizeObserver', class { observe() {}; disconnect = disconnect })
  document.body.style.margin = '0'
  vi.spyOn(document.body, 'getBoundingClientRect').mockReturnValue({ height: 1234 } as DOMRect)
  const post = vi.spyOn(window, 'postMessage')
  cleanups.push(observeContentSize('https://host.example'))
  vi.advanceTimersByTime(20)
  expect(post).toHaveBeenCalledWith({ type: FRAME_SIZE, height: 1234 }, 'https://host.example')
  const emit = (data: unknown, origin = 'https://host.example') => window.dispatchEvent(new MessageEvent('message', { source: window, origin, data }))
  emit({ type: FRAME_VIEWPORT, top: 300, height: 600 }, 'https://attacker.example')
  emit({ type: FRAME_VIEWPORT, top: -1, height: 600 })
  expect(document.documentElement.dataset.amberLayout).toBeUndefined()
  emit({ type: FRAME_VIEWPORT, top: 300, height: 600 })
  expect(document.documentElement.style.getPropertyValue('--amber-viewport-top')).toBe('300px')
  cleanups.pop()!(); expect(disconnect).toHaveBeenCalledOnce()
})
it('makes a full page frame at least as tall as the visible page area, minus the frames below it', () => {
  vi.useFakeTimers()
  const scroller = document.createElement('div'); scroller.dataset.pageScroll = ''; scroller.style.paddingBottom = '64px'
  const container = document.createElement('div')
  const frame = document.createElement('iframe'), feature = document.createElement('iframe')
  container.append(frame, feature); scroller.append(container); document.body.append(scroller)
  Object.defineProperty(scroller, 'clientHeight', { configurable: true, value: 900 })
  Object.defineProperty(scroller, 'scrollTop', { configurable: true, value: 0 })
  vi.spyOn(scroller, 'getBoundingClientRect').mockReturnValue({ top: 50, bottom: 950 } as DOMRect)
  vi.spyOn(frame, 'getBoundingClientRect').mockReturnValue({ top: 130, height: 300 } as DOMRect)
  vi.spyOn(feature, 'getBoundingClientRect').mockReturnValue({ top: 430, height: 200 } as DOMRect)
  cleanups.push(fitContribution(frame, 'https://package.example', { fill: true }))
  vi.advanceTimersByTime(20)
  // 900 visible - 80 above the frame - 64 bottom padding - 200 for the feature.
  expect(frame.style.minHeight).toBe('556px')
  const emit = (data: unknown) => window.dispatchEvent(new MessageEvent('message', { source: frame.contentWindow, origin: 'https://package.example', data }))
  emit({ type: FRAME_SIZE, height: 120 }); vi.advanceTimersByTime(20)
  expect([frame.style.height, frame.style.minHeight]).toEqual(['120px', '556px'])
  // Scrolling does not change the floor: it depends on the frame's place in the page.
  Object.defineProperty(scroller, 'scrollTop', { configurable: true, value: 300 })
  vi.mocked(frame.getBoundingClientRect).mockReturnValue({ top: -170, height: 556 } as DOMRect)
  document.dispatchEvent(new Event('scroll')); vi.advanceTimersByTime(20)
  expect(frame.style.minHeight).toBe('556px')
})
