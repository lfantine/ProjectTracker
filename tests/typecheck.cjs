const fs = require('node:fs')
const ts = require('typescript')

// Each environment has its own compiler options: the shared contracts must not
// see DOM or Node types, the main process must not see DOM types, etc.
const projects = [
  ['shared', 'Contrats partagés'],
  ['main', 'Processus principal'],
  ['preload', 'Pont isolé du runtime'],
  ['renderer', 'Interface'],
  ['sdk', 'SDK des packages'],
  ['packages', 'Packages livrés'],
].filter(([dir]) => fs.existsSync(`${dir}/tsconfig.json`))
const only = process.argv.slice(2)
const format = {
  getCanonicalFileName: file => file,
  getCurrentDirectory: ts.sys.getCurrentDirectory,
  getNewLine: () => '\n',
}
let total = 0
for (const [dir, label] of projects) {
  if (only.length && !only.includes(dir)) continue
  const config = ts.readConfigFile(`${dir}/tsconfig.json`, ts.sys.readFile)
  if (config.error) {
    console.error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'))
    process.exit(1)
  }
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, dir)
  // Check source files once, excluding duplicate dev/build validators generated by Next.
  const program = ts.createProgram(parsed.fileNames.filter(file => !file.includes('/.next/')), parsed.options)
  const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)]
  if (diagnostics.length) console.error(ts.formatDiagnosticsWithColorAndContext(diagnostics, format))
  console.log(`${label} (${dir}) : ${diagnostics.length} erreur(s) de type`)
  total += diagnostics.length
}
console.log(`${total} source type errors`)
process.exitCode = total ? 1 : 0
