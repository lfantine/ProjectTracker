import React from 'react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { PackageMarketplace } from '../renderer/components/PackageMarketplace'
import combined from './fixtures/manifests/valid/combined.json'
const mocks = vi.hoisted(() => ({ snapshot: vi.fn(), importArchive: vi.fn(), activate: vi.fn(), importFolder: vi.fn() }))
vi.mock('../renderer/lib/store', () => ({ useData: () => ({ data: { projects: [] } }) }))
vi.mock('../renderer/lib/composition', () => ({ useComposition: () => ({ snapshot: { instances: [], dashboards: [], contributions: [] }, mutate: vi.fn(), pending: false }) }))
vi.mock('next/link', () => ({ default: ({ children, ...props }: React.PropsWithChildren<{ href: string }>) => <a {...props}>{children}</a> }))
const ready = (overrides = {}) => ({ ok: true, value: { phase: 'ready', packages: [], versions: [], details: [], catalogue: { status: 'unlinked' }, bundled: [], ...overrides } })
afterEach(cleanup)
beforeEach(() => {
  for (const mock of Object.values(mocks)) mock.mockReset()
  mocks.snapshot.mockResolvedValue(ready({ packages: [{ id: combined.id, name: combined.name, state: 'disabled', activeVersion: null, reason: null, revision: 1 }], details: [{ manifest: combined, status: 'ready' }] }))
  Object.defineProperty(window, 'api', { configurable: true, value: { packages: { snapshot: mocks.snapshot, importArchive: mocks.importArchive, activate: mocks.activate, importFolder: mocks.importFolder, onChanged: () => () => {} } } })
})
it('shows one card per package with its status and a single next action, without any project', async () => {
  render(<PackageMarketplace />)
  const installed = await screen.findByRole('region', { name: 'Installés' })
  expect(within(installed).getByText('À activer')).toBeTruthy()
  expect(within(installed).getByRole('button', { name: 'Activer' })).toBeTruthy()
  fireEvent.click(within(installed).getByRole('button', { name: `Détails de ${combined.name}` }))
  const dialog = screen.getByRole('dialog')
  for (const contribution of combined.contributions) expect(within(dialog).getByText(contribution.name, { exact: true })).toBeTruthy()
  expect(within(dialog).getByText('Accès demandés')).toBeTruthy()
  expect(within(dialog).getByText('Lire les projets')).toBeTruthy()
  expect(within(dialog).getByText('Blocs projet')).toBeTruthy()
})
it('installs an available package in one gesture: import then activation', async () => {
  mocks.snapshot.mockResolvedValue(ready({ catalogue: { status: 'ok', entries: [{ status: 'available', fileName: 'a.zip', manifest: combined, selection: 'token', publisherVerified: false, sourceSha256: 'x', contentSha256: 'y', issues: [] }] } }))
  mocks.importFolder.mockResolvedValue({ ok: true, value: { packageId: combined.id, version: combined.version, status: 'ready' } })
  mocks.activate.mockResolvedValue({ ok: true, value: { status: 'active' } })
  render(<PackageMarketplace />)
  const available = await screen.findByRole('region', { name: 'Disponibles' })
  fireEvent.click(within(available).getByRole('button', { name: 'Installer' }))
  await screen.findByText(`${combined.name} est installé et activé.`)
  expect(mocks.importFolder).toHaveBeenCalledWith({ selection: 'token' })
  expect(mocks.activate).toHaveBeenCalledWith({ packageId: combined.id, version: combined.version })
})
it('imports a ZIP, activates it and opens its card; a cancelled picker does nothing', async () => {
  mocks.importArchive.mockResolvedValueOnce({ ok: true, value: null })
  render(<PackageMarketplace />)
  await screen.findByRole('region', { name: 'Installés' })
  fireEvent.click(screen.getByRole('button', { name: 'Importer un ZIP' }))
  await waitFor(() => expect(mocks.importArchive).toHaveBeenCalledTimes(1))
  expect(mocks.activate).not.toHaveBeenCalled()
  mocks.importArchive.mockResolvedValueOnce({ ok: true, value: { packageId: combined.id, version: combined.version, status: 'ready' } })
  mocks.activate.mockResolvedValue({ ok: true, value: { status: 'active' } })
  await waitFor(() => expect(screen.getByRole('button', { name: 'Importer un ZIP' })).not.toBeDisabled())
  fireEvent.click(screen.getByRole('button', { name: 'Importer un ZIP' }))
  await screen.findByText('Module installé et activé.')
  expect(mocks.activate).toHaveBeenCalledWith({ packageId: combined.id, version: combined.version })
  expect(screen.getByRole('dialog')).toBeTruthy()
})
it('explains a blocking problem in words instead of an error code', async () => {
  mocks.snapshot.mockResolvedValue(ready({ packages: [{ id: combined.id, name: combined.name, state: 'disabled', activeVersion: null, reason: null, revision: 1 }], details: [{ manifest: combined, status: 'ready', issues: [{ code: 'DEPENDENCY_MISSING', packageId: combined.id, dependency: 'builtin.week' }] }] }))
  render(<PackageMarketplace />)
  expect(await screen.findByText('Nécessite builtin.week')).toBeTruthy()
  expect(screen.getByRole('button', { name: 'Activer' })).toBeDisabled()
})
it('keeps management unavailable visibly when no qualified native handler exists', async () => {
  mocks.snapshot.mockRejectedValue(Error('/private/path/never-expose'))
  render(<PackageMarketplace />)
  expect(await screen.findByRole('alert')).toHaveTextContent('non activée dans ce profil')
  expect(screen.queryByText('/private/path/never-expose')).toBeNull()
  expect(screen.getByRole('button', { name: 'Importer un ZIP' })).toBeDisabled()
})
