import { useState } from 'react'
import { fireEvent, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterAll, beforeAll, expect, it, vi } from 'vitest'
import { WeekSchedule } from '../renderer/components/WeekSchedule'
import type { WeekSlot } from '../renderer/lib/weekSchedule'
beforeAll(() => vi.stubGlobal('PointerEvent', MouseEvent))
afterAll(() => vi.unstubAllGlobals())
const lecture: WeekSlot = { id: 'a', title: 'Lecture', day: 0, start: '09:00', end: '10:00' }
function Schedule({ initial = [] }: { initial?: WeekSlot[] }) { const [slots, setSlots] = useState(initial); return <WeekSchedule slots={slots} onChange={setSlots} projects={[{ id: 'project-1', name: 'Mon projet' }]} /> }
function draw(start: number, end: number) {
  const day = screen.getByLabelText('Créneaux du Lundi')
  fireEvent.pointerDown(day, { button: 0, clientY: start * .8 })
  fireEvent.pointerMove(day, { clientY: end * .8 })
  fireEvent.pointerUp(day, { clientY: end * .8 })
}
it('Interface : dessine un créneau puis sélectionne, modifie avec Espace et supprime avec Delete', async () => {
  const user = userEvent.setup(); render(<Schedule />)
  expect(screen.queryByLabelText('Objectif')).not.toBeInTheDocument()
  draw(540, 600)
  expect(screen.getByLabelText('Début')).toHaveValue('09:00')
  expect(screen.getByLabelText('Fin')).toHaveValue('10:00')
  await user.type(screen.getByLabelText('Objectif'), 'Lecture')
  await user.click(screen.getByRole('button', { name: 'Ajouter' }))
  const slot = screen.getByRole('button', { name: /Lecture, Lundi/ })
  await user.click(slot)
  expect(slot).toHaveAttribute('aria-pressed', 'true')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  await user.keyboard(' ')
  expect(screen.getByRole('dialog')).toBeInTheDocument()
  await user.clear(screen.getByLabelText('Objectif')); await user.type(screen.getByLabelText('Objectif'), 'Sport')
  await user.click(screen.getByRole('button', { name: 'Enregistrer' }))
  await user.click(screen.getByRole('button', { name: /Sport, Lundi/ }))
  await user.keyboard('{Delete}')
  expect(screen.queryByRole('button', { name: /Sport, Lundi/ })).not.toBeInTheDocument()
})
it('Interface : dessine vers le haut et annule sans enregistrer', async () => {
  const user = userEvent.setup(); render(<Schedule />)
  draw(600, 540)
  expect(screen.getByLabelText('Début')).toHaveValue('09:00')
  expect(screen.getByLabelText('Fin')).toHaveValue('10:00')
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: /Lundi,/ })).not.toBeInTheDocument()
})
it('Interface : refuse les chevauchements et ne supprime pas pendant la saisie', async () => {
  const user = userEvent.setup(); render(<Schedule initial={[lecture]} />)
  draw(570, 630)
  await user.type(screen.getByLabelText('Objectif'), 'Sport')
  await user.click(screen.getByRole('button', { name: 'Ajouter' }))
  expect(screen.getByRole('alert')).toHaveTextContent('chevauche')
  await user.click(screen.getByLabelText('Objectif')); await user.keyboard('{Backspace}')
  expect(screen.getByRole('button', { name: /Lecture, Lundi/ })).toBeInTheDocument()
  await user.keyboard('{Escape}')
  await user.click(screen.getByRole('button', { name: /Lecture, Lundi/ }))
  await user.keyboard('{Escape}{Delete}')
  expect(screen.getByRole('button', { name: /Lecture, Lundi/ })).toBeInTheDocument()
})
it('Interface : annule un geste interrompu sans créer de créneau', () => {
  render(<Schedule />)
  const day = screen.getByLabelText('Créneaux du Lundi')
  fireEvent.pointerDown(day, { button: 0, clientY: 432 })
  fireEvent.pointerCancel(day)
  fireEvent.pointerUp(day, { clientY: 480 })
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})

it('Interface : un clic ou un mouvement minime désélectionne sans création', async () => {
  const user = userEvent.setup(); render(<Schedule initial={[lecture]} />)
  const slot = screen.getByRole('button', { name: /Lecture, Lundi/ })
  const day = screen.getByLabelText('Créneaux du Lundi')
  for (const offset of [0, 3]) {
    await user.click(slot)
    fireEvent.pointerDown(day, { button: 0, clientY: 480 })
    fireEvent.pointerMove(day, { clientY: 480 + offset })
    fireEvent.pointerUp(day, { clientY: 480 + offset })
    expect(slot).toHaveAttribute('aria-pressed', 'false')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  }
})
it('Interface : les détails sont optionnels, vides au départ et conservés après édition', async () => {
  const user = userEvent.setup(); render(<Schedule />)
  draw(540, 600)
  for (const field of ['Description', 'Projet lié', 'Lieu / adresse', 'Personnes', 'Lien']) expect(screen.getByLabelText(field)).toHaveValue('')
  await user.type(screen.getByLabelText('Objectif'), 'Réunion')
  await user.type(screen.getByLabelText('Description'), 'Préparer la semaine')
  await user.selectOptions(screen.getByLabelText('Projet lié'), 'project-1')
  await user.type(screen.getByLabelText('Lieu / adresse'), '12 rue du Parc')
  await user.type(screen.getByLabelText('Personnes'), 'Alice{Enter}Bob')
  await user.type(screen.getByLabelText('Lien'), 'https://example.com')
  await user.click(screen.getByRole('button', { name: 'Ajouter' }))
  await user.click(screen.getByRole('button', { name: /Réunion, Lundi/ }))
  await user.keyboard(' ')
  expect(screen.getByLabelText('Description')).toHaveValue('Préparer la semaine')
  expect(screen.getByLabelText('Projet lié')).toHaveValue('project-1')
  expect(screen.getByLabelText('Lieu / adresse')).toHaveValue('12 rue du Parc')
  expect(screen.getByLabelText('Personnes')).toHaveValue('Alice\nBob')
  expect(screen.getByLabelText('Lien')).toHaveValue('https://example.com')
  await user.clear(screen.getByLabelText('Description'))
  await user.click(screen.getByRole('button', { name: 'Enregistrer' }))
  await user.click(screen.getByRole('button', { name: /Réunion, Lundi/ })); await user.keyboard(' ')
  expect(screen.getByLabelText('Description')).toHaveValue('')
  expect(screen.getByLabelText('Personnes')).toHaveValue('Alice\nBob')
})

it('Interface : couleur grise par défaut, code hexadécimal validé et conservé', async () => {
  const user = userEvent.setup(); render(<Schedule initial={[lecture]} />)
  const slot = screen.getByRole('button', { name: /Lecture, Lundi/ })
  expect(slot).toHaveStyle({ backgroundColor: '#d1d5db' })
  await user.click(slot); await user.keyboard(' ')
  expect(screen.getByLabelText('Code couleur')).toHaveValue('#d1d5db')
  await user.clear(screen.getByLabelText('Code couleur'))
  await user.type(screen.getByLabelText('Code couleur'), 'incorrect')
  await user.click(screen.getByRole('button', { name: 'Enregistrer' }))
  expect(screen.getByRole('alert')).toHaveTextContent('hexadécimale')
  await user.clear(screen.getByLabelText('Code couleur'))
  await user.type(screen.getByLabelText('Code couleur'), '#369')
  await user.click(screen.getByRole('button', { name: 'Enregistrer' }))
  expect(slot).toHaveStyle({ backgroundColor: '#336699' })
  await user.click(slot); await user.keyboard(' ')
  expect(screen.getByLabelText('Code couleur')).toHaveValue('#336699')
  expect(screen.getByLabelText('Couleur')).toHaveValue('#336699')
})
